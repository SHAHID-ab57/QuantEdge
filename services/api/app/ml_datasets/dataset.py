"""The ML dataset builder — features, targets, validation, and a chronological split, in one pass.

This is the platform's **only supported mechanism for producing a dataset
used in AI training** (see `ARCHITECTURE.md` § "ML Dataset Builder"). It
does not build features itself, does not invent a second validation
mechanism, and does not reimplement splitting — it *composes* three
already-existing engines:

1. `FeatureDatasetBuilder` builds the input matrix, unchanged.
2. Target columns are generated by `TargetPipeline` and appended onto that
   same matrix as ordinary columns (see `app/ml_datasets/base.py` for why
   targets live in their own registry rather than the feature one).
3. `DatasetValidator` (the existing Dataset Validation Engine) runs its
   full rule suite over the assembled feature+target matrix — the same
   structural/data-quality/time-series/feature checks `/validation`
   already runs, here applied automatically rather than left to a
   researcher to remember to run separately.
4. `ChronologicalSplitter` slices the validated matrix into train/
   validation/test, contiguously and in time order.

Two trims happen before any of that assembly is considered final, mirroring
each other at opposite ends of the series: **warmup trimming** (leading
rows dropped because a feature isn't defined yet — `FeatureDatasetBuilder`'s
own job) and **horizon trimming** (trailing rows dropped because a target
isn't defined yet — this module's job, added here because only the ML
Dataset Builder has both a feature-warmup-trimmed matrix and a target
pipeline in scope at the same time).
"""

import logging
import uuid
from dataclasses import dataclass, field, replace
from datetime import UTC, datetime
from time import perf_counter
from typing import Any

from app.dataset_validation.engine import DatasetValidator
from app.dataset_validation.report import ValidationReport
from app.features.ai_extensions import DatasetSplit, SplitRatios
from app.features.base import FeatureColumn, FeatureValue, OHLCVPoint
from app.features.dataset import FeatureDataset, FeatureDatasetBuilder, FeatureRequest
from app.features.quality import FeatureFailure
from app.ml_datasets.errors import (
    DuplicateTargetColumnError,
    EmptyMLDatasetError,
    InsufficientTargetDataError,
    InvalidTargetParameterError,
    TargetExecutionError,
    TargetNotFoundError,
)
from app.ml_datasets.pipeline import TARGET_PIPELINE_VERSION, TargetPipeline
from app.ml_datasets.split import ChronologicalSplitter

logger = logging.getLogger("app.ml_datasets.dataset")

#: Mirrors `app.features.dataset._REQUEST_ERRORS` exactly, for the same
#: reason: one bad target among several requested must not abort the
#: others. `DuplicateTargetColumnError` is deliberately absent — a column
#: collision has no partial result that makes sense, so it still raises.
_TARGET_REQUEST_ERRORS = (
    TargetNotFoundError,
    InvalidTargetParameterError,
    InsufficientTargetDataError,
    TargetExecutionError,
)

#: This builder's own version, independent of `FeaturePipeline.PIPELINE_VERSION`,
#: `TargetPipeline.TARGET_PIPELINE_VERSION`, and `DatasetValidator.ENGINE_VERSION`
#: — bump it when *this composition* changes (e.g. the trim/validate/split
#: order) even if none of the three engines it composes do.
ML_BUILDER_VERSION = "1.0.0"


@dataclass(frozen=True, slots=True)
class TargetRequest:
    """One prediction target to include in an ML dataset, with its parameters."""

    target: str
    params: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True, slots=True)
class DatasetTargetInfo:
    """How one requested target actually resolved, for the dataset's provenance record."""

    target: str
    label: str
    version: str
    params: dict[str, Any]
    columns: list[str]
    horizon: int
    execution_time_ms: float


@dataclass(frozen=True, slots=True)
class MLDataset:
    """A versioned, leakage-checked, split, ready-for-training dataset.

    ``dataset`` is the full (pre-split) feature+target matrix — every
    feature column `FeatureDatasetBuilder` produced, plus every target
    column this builder appended, over exactly the rows that survived both
    warmup and horizon trimming. ``feature_columns``/``target_columns``
    name which of ``dataset.columns`` is which, since `FeatureDataset`
    itself has no notion of "input vs. label" (see `base.py`).
    """

    #: Unique per build — a UUID4, not a content hash, matching
    #: `FeatureDataset.dataset_id`'s own reproducibility contract exactly:
    #: this identifies *this build*, not merely "this configuration."
    ml_dataset_id: str
    dataset: FeatureDataset
    feature_columns: tuple[str, ...]
    target_columns: tuple[str, ...]
    targets: list[DatasetTargetInfo]
    target_failures: list[FeatureFailure]
    #: Largest horizon across every requested target — the reason this
    #: many trailing rows could never have a defined label.
    max_horizon: int
    #: Rows dropped because at least one requested target was still undefined
    #: (mirrors `FeatureDataset.rows_dropped`'s meaning, at the other end).
    rows_dropped_for_horizon: int
    target_pipeline_version: str
    builder_version: str
    split_ratios: SplitRatios
    split: DatasetSplit
    validation: ValidationReport
    created_at: datetime


class MLDatasetBuilder:
    """Composes feature building, target generation, validation, and splitting."""

    def __init__(
        self,
        feature_builder: FeatureDatasetBuilder,
        target_pipeline: TargetPipeline,
        validator: DatasetValidator,
        splitter: ChronologicalSplitter | None = None,
    ) -> None:
        self._feature_builder = feature_builder
        self._target_pipeline = target_pipeline
        self._validator = validator
        self._splitter = splitter or ChronologicalSplitter()

    @property
    def target_pipeline(self) -> TargetPipeline:
        """The pipeline this builder runs target generators through."""
        return self._target_pipeline

    @property
    def feature_builder(self) -> FeatureDatasetBuilder:
        """The builder this composes for the feature half of the matrix."""
        return self._feature_builder

    def required_horizon(self, requests: list[TargetRequest]) -> int:
        """The largest horizon across every *resolvable* requested target.

        Mirrors `FeatureDatasetBuilder.required_warmup` exactly: a request
        that will fail outright doesn't contribute to the max here, so one
        bad target request can't defeat this builder's own partial-success
        handling before `build` ever runs it.
        """
        horizons: list[int] = []
        for request in requests:
            try:
                horizons.append(self._target_pipeline.horizon_for(request.target, request.params))
            except _TARGET_REQUEST_ERRORS:
                continue
        return max(horizons, default=0)

    def build(
        self,
        symbol: str,
        timeframe: str,
        candles: list[OHLCVPoint],
        feature_requests: list[FeatureRequest],
        target_requests: list[TargetRequest],
        *,
        drop_warmup: bool = True,
        drop_undefined_targets: bool = True,
        split_ratios: SplitRatios | None = None,
    ) -> MLDataset:
        """Build, validate, and split one ML dataset.

        Order matters and is fixed, mirroring `FeaturePipeline`'s own
        "no branch on what's being built" discipline: build features (with
        their own warmup trimming) → generate targets over the *original*
        candle range (so horizon look-ahead is computed correctly) → align
        target values onto the warmup-trimmed rows by timestamp → trim
        trailing rows with an undefined target → validate the assembled
        matrix → split it chronologically.
        """
        ratios = split_ratios or SplitRatios()
        feature_dataset = self._feature_builder.build(
            symbol, timeframe, candles, feature_requests, drop_warmup=drop_warmup
        )

        owner_of_column: dict[str, str] = {}
        for info in feature_dataset.features:
            for name in info.columns:
                owner_of_column[name] = info.feature

        target_infos: list[DatasetTargetInfo] = []
        target_failures: list[FeatureFailure] = []
        raw_series: dict[str, tuple[FeatureColumn, list[FeatureValue]]] = {}
        max_horizon = 0

        generation_started = perf_counter()
        for request in target_requests:
            try:
                run = self._target_pipeline.run(request.target, candles, request.params)
            except _TARGET_REQUEST_ERRORS as exc:
                target_failures.append(
                    FeatureFailure(
                        feature=request.target,
                        params=dict(request.params),
                        error_code=exc.code,
                        error_detail=exc.message,
                    )
                )
                continue
            produced: list[str] = []
            for series in run.output.series:
                name = series.column.name
                previous = owner_of_column.get(name)
                if previous is not None:
                    raise DuplicateTargetColumnError(name, previous, request.target)
                owner_of_column[name] = request.target
                raw_series[name] = (series.column, series.values)
                produced.append(name)
            max_horizon = max(max_horizon, run.horizon)
            target_infos.append(
                DatasetTargetInfo(
                    target=request.target,
                    label=run.metadata.label,
                    version=run.metadata.version,
                    params=run.params,
                    columns=produced,
                    horizon=run.horizon,
                    execution_time_ms=run.execution_time_ms,
                )
            )
        generation_time_ms = (perf_counter() - generation_started) * 1000

        target_columns = [column for column, _ in raw_series.values()]
        target_names = list(raw_series)

        # Targets are generated over the *original* candle range so a
        # horizon lookup is always correct, then realigned by timestamp
        # onto whichever rows survived feature-warmup trimming — the two
        # trims happen independently and must be reconciled before the
        # two matrices can be joined into one.
        index_by_timestamp = {candle.open_time: index for index, candle in enumerate(candles)}
        aligned: dict[str, list[FeatureValue]] = {name: [] for name in target_names}
        for timestamp in feature_dataset.timestamps:
            original_index = index_by_timestamp[timestamp]
            for name in target_names:
                aligned[name].append(raw_series[name][1][original_index])

        kept_timestamps = list(feature_dataset.timestamps)
        kept_feature_rows = list(feature_dataset.rows)
        kept_target_rows = [
            [aligned[name][row_index] for name in target_names]
            for row_index in range(len(kept_timestamps))
        ]

        rows_dropped_for_horizon = 0
        if drop_undefined_targets and target_names:
            keep_indices = [
                index
                for index, row in enumerate(kept_target_rows)
                if all(value is not None for value in row)
            ]
            rows_dropped_for_horizon = len(kept_timestamps) - len(keep_indices)
            kept_timestamps = [kept_timestamps[index] for index in keep_indices]
            kept_feature_rows = [kept_feature_rows[index] for index in keep_indices]
            kept_target_rows = [kept_target_rows[index] for index in keep_indices]

        if drop_undefined_targets and target_columns and not kept_timestamps:
            raise EmptyMLDatasetError(len(candles), feature_dataset.warmup_candles, max_horizon)

        combined_columns = [*feature_dataset.columns, *target_columns]
        combined_rows = [
            [*feature_row, *target_row]
            for feature_row, target_row in zip(kept_feature_rows, kept_target_rows, strict=True)
        ]

        assembled = replace(
            feature_dataset,
            columns=combined_columns,
            timestamps=kept_timestamps,
            rows=combined_rows,
            quality=replace(
                feature_dataset.quality,
                rows_returned=len(combined_rows),
                rows_removed=feature_dataset.quality.rows_removed + rows_dropped_for_horizon,
                feature_failures=[*feature_dataset.quality.feature_failures, *target_failures],
                generation_time_ms=feature_dataset.quality.generation_time_ms + generation_time_ms,
            ),
        )

        validation = self._validator.validate(assembled)
        split = self._splitter.split(assembled, ratios)

        logger.info(
            "Built ML dataset (symbol=%s timeframe=%s targets=%d columns=%d rows=%d "
            "dropped_for_horizon=%d failures=%d passed=%s)",
            symbol,
            timeframe,
            len(target_requests),
            len(combined_columns),
            len(combined_rows),
            rows_dropped_for_horizon,
            len(target_failures),
            validation.passed,
        )

        return MLDataset(
            ml_dataset_id=str(uuid.uuid4()),
            dataset=assembled,
            feature_columns=tuple(column.name for column in feature_dataset.columns),
            target_columns=tuple(target_names),
            targets=target_infos,
            target_failures=target_failures,
            max_horizon=max_horizon,
            rows_dropped_for_horizon=rows_dropped_for_horizon,
            target_pipeline_version=TARGET_PIPELINE_VERSION,
            builder_version=ML_BUILDER_VERSION,
            split_ratios=ratios,
            split=split,
            validation=validation,
            created_at=datetime.now(UTC),
        )
